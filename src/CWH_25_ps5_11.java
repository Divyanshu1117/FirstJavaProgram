public class CWH_25_ps5_11 {
    public static void main(String[] args) {
        // For Loop:-
        int sum = 0;
        int n = 3;
        for (int i = 0; i < n; i++) {
            sum = sum + (2 * i);
        }
        System.out.print("Sum Of Even Number Is:- ");
        System.out.println(sum + ".");
    }
}