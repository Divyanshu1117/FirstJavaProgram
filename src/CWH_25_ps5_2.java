public class CWH_25_ps5_2 {
    public static void main(String[] args) {
        // While Loop:-
        int sum = 0;
        int n = 3;
        int i = 0;
        while (i < n) {
            sum = sum + (2 * i);
            i++;
        }
        System.out.print("Sum Of Even Numbers Is: ");
        System.out.println(sum + ".");
    }
}